namespace RayBork;

/// <summary>
/// Identifies a mouse button. Values are zero-based and start with the primary button.
/// </summary>
public enum MouseButton {
    /// <summary>
    /// The primary (left) button.
    /// </summary>
    Left = 0,

    /// <summary>
    /// The middle button.
    /// </summary>
    Middle = 1,

    /// <summary>
    /// The secondary (right) button.
    /// </summary>
    Right = 2,

    /// <summary>
    /// The first extra button.
    /// </summary>
    X1 = 3,

    /// <summary>
    /// The second extra button.
    /// </summary>
    X2 = 4,
}
